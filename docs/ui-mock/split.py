"""Split index.html's <section> screens into one standalone file each, for screenshotting.

The CSS is inlined into every generated file on purpose: the screenshot preview renders local
files as static snapshots, so it does not fetch a linked stylesheet and a <link> would quietly
produce unstyled screenshots. For the same reason the files cannot share one document and switch
screens with a URL hash - :target does not run in a snapshot.

Usage: python docs/ui-mock/split.py
"""
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Penumbra Organizer - {id}</title>
<!-- GENERATED by split.py from index.html - edit index.html, not this file. -->
<style>
{style}
</style>
</head>
<body>
<section id="{id}">{inner}</section>
</body>
</html>
"""


def main():
    src = io.open(os.path.join(HERE, "index.html"), encoding="utf-8").read()

    style = re.search(r"<style>(.*?)</style>", src, re.S).group(1)
    # In a one-screen file the section is always the one being shown.
    style = style.replace("  section { display: none; }\n", "  section { display: block; }\n")
    style = re.sub(r"\s*/\* Default screen.*?\n.*?\n", "\n", style).strip()
    io.open(os.path.join(HERE, "style.css"), "w", encoding="utf-8", newline="").write(style + "\n")

    for sid, inner in re.findall(r'<section id="([^"]+)">(.*?)</section>', src, re.S):
        path = os.path.join(HERE, sid + ".html")
        io.open(path, "w", encoding="utf-8", newline="").write(
            TEMPLATE.format(id=sid, inner=inner, style=style))
        print("wrote", os.path.basename(path))


if __name__ == "__main__":
    main()
